"""Extract a small set of real Yaskawa incremental encoder frames for the sim tests.

The source captures (Saleae Manchester-analyser CSVs, ~20 MB each) live in the
yaskawa-incremental-encoder project, so only the selected frames are committed.

usage: python make_yaskawa_fixtures.py [path/to/yaskawa-incremental-encoder]
"""
import os
import sys

from yaskawa_protocol import decode, read_capture_packets

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_REF = os.path.expanduser("~/git/yaskawa-incremental-encoder")
OUT = os.path.join(HERE, "data", "yaskawa_incremental_frames.txt")

CAPTURES = [
    "4mbit-1bit-data-lsb-rx-no-rotation.csv",
    "4mbit-1bit-data-lsb-rx-rotate_cw-10sec_1rev.csv",
    "4mbit-1bit-data-lsb-rx-rotate_cw-10sec.csv",
    "4mbit-1bit-data-lsb-rx-rotate-10sec.csv",
    "4mbit-1bit-data-lsb-rx-drill-cw.csv",
    "4mbit-1bit-data-lsb-rx-drill-ccw.csv",
]
STRIDE_FRAMES = 16      # evenly spaced frames per capture
LONGEST_FRAMES = 4      # plus the frames with the most stuffed bits


def main():
    ref = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_REF
    lines = [
        "# Real Yaskawa UTSIH-B17CK incremental encoder responses, one per line: <capture> <on-wire bits>",
        "# Bits start at the analyser's first decoded bit ('1111110'); prepend a preamble and '0' to replay.",
        "# Generated by make_yaskawa_fixtures.py from the yaskawa-incremental-encoder logic analyser dumps.",
    ]
    for name in CAPTURES:
        good = []
        for p in read_capture_packets(os.path.join(ref, "logic analyser dumps", name))[1:-1]:
            try:
                if decode(p)["crc_ok"]:
                    good.append(p)
            except ValueError:
                pass    # truncated at the capture boundary
        stride = max(1, len(good) // STRIDE_FRAMES)
        picked = good[::stride][:STRIDE_FRAMES]
        picked += [p for p in sorted(good, key=len, reverse=True) if p not in picked][:LONGEST_FRAMES]
        lines += [f"{name} {p}" for p in picked]
        print(f"{name}: {len(good)} CRC-good frames, kept {len(picked)}")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
