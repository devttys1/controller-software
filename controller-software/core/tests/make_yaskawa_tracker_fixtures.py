"""Build data/yaskawa_tracker_sequences.csv for yaskawa_tracker_test.cpp.

Takes consecutive CRC-good frames from the yaskawa-incremental-encoder logic
analyser captures. For every frame it records:
  reference_position  what that project's own yask_track_update() (compiled from
                      its source) reports when fed this sequence
  truth               the full-rate position at that frame (relative to the first),
                      which is exact because full-rate steps are < 0.06 rev

Thinned-out sequences (every Nth frame) push steps past half a revolution, where
single_turn alone is ambiguous.

usage: python make_yaskawa_tracker_fixtures.py [path/to/yaskawa-incremental-encoder]
"""
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "controller-firmware", "python", "sim"))
from yaskawa_protocol import decode, read_capture_packets  # noqa: E402

DEFAULT_REF = os.path.expanduser("~/git/yaskawa-incremental-encoder")
OUT = os.path.join(HERE, "data", "yaskawa_tracker_sequences.csv")

CAPTURES = {
    "slow_cw": "4mbit-1bit-data-lsb-rx-rotate_cw-10sec_1rev.csv",
    "drill_cw": "4mbit-1bit-data-lsb-rx-drill-cw.csv",
    "drill_ccw": "4mbit-1bit-data-lsb-rx-drill-ccw.csv",
}

# (sequence, decimation, max frames at full rate)
SEQUENCES = [
    ("slow_cw", 4, None),
    ("drill_cw", 1, 1000),
    ("drill_cw", 30, None),     # steps ~0.37 rev
    ("drill_cw", 45, None),     # steps ~0.55 rev, past half a revolution
    ("drill_cw", 200, None),    # steps ~2.5 rev
    ("drill_ccw", 6, None),
]

HARNESS = r"""
#include <stdio.h>
#include "yaskawa_enc.h"
int main(void){
    yask_tracker_t t; yask_track_reset(&t);
    unsigned long st; unsigned mt;
    while (scanf("%lu %u", &st, &mt) == 2) {
        yask_frame_t f = {0}; f.single_turn = st; f.multi_turn = (uint8_t)mt;
        printf("%lld\n", (long long)yask_track_update(&t, &f));
    }
    return 0;
}
"""


def reference_positions(exe, frames):
    stdin = "".join(f"{st} {mt}\n" for st, mt in frames)
    out = subprocess.run([exe], input=stdin, capture_output=True, text=True, check=True).stdout
    return [int(x) for x in out.split()]


def main():
    ref = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_REF
    with tempfile.TemporaryDirectory() as tmp:
        src, exe = os.path.join(tmp, "harness.c"), os.path.join(tmp, "harness")
        with open(src, "w") as f:
            f.write(HARNESS)
        subprocess.run(["cc", "-O2", "-DYASK_HOST_TEST", f"-I{ref}/Core/Inc", src,
                        f"{ref}/Core/Src/yaskawa_decode.c", "-o", exe], check=True)

        lines = ["# sequence,decimation,single_turn,rot3,mt4,reference_position,truth",
                 "# generated by make_yaskawa_tracker_fixtures.py from the yaskawa-incremental-encoder captures"]
        cache = {}
        for name, decimation, limit in SEQUENCES:
            capture = CAPTURES[name]
            if capture not in cache:
                frames = []
                for p in read_capture_packets(os.path.join(ref, "logic analyser dumps", capture))[1:-1]:
                    try:
                        d = decode(p)
                    except ValueError:
                        continue
                    if d["crc_ok"]:
                        frames.append((d["single_turn"], d["mt4"], d["rot3"]))
                cache[capture] = (frames, reference_positions(exe, [f[:2] for f in frames]))
            frames, truth = cache[capture]
            frames, truth = frames[:limit], truth[:limit]
            picked = list(range(0, len(frames), decimation))
            positions = reference_positions(exe, [frames[i][:2] for i in picked])
            for i, pos in zip(picked, positions):
                st, mt, rot3 = frames[i]
                lines.append(f"{name},{decimation},{st},{rot3},{mt},{pos},{truth[i] - truth[0]}")
            print(f"{name} /{decimation}: {len(picked)} frames, "
                  f"reference {positions[-1] / 131072:+.3f} rev, truth {(truth[picked[-1]] - truth[0]) / 131072:+.3f} rev")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
